import { firefox } from 'playwright';
await fetch('http://localhost:1420/api/slot', { method: 'POST', headers: { 'content-type': 'application/json' }, body: JSON.stringify({ slot: 'E' }) });
const browser = await firefox.launch({ headless: true });
const page = await browser.newPage({ viewport: { width: 1600, height: 950 } });
page.on('pageerror', e => console.log('ERR', String(e).slice(0,150)));
await page.goto('http://localhost:1420/src/?mode=Vibes', { waitUntil: 'domcontentloaded' });
await page.waitForTimeout(4000);
// native typing probe on click-target
await page.fill('#urlInput', 'http://localhost:1420/api/test/click-target');
await page.press('#urlInput', 'Enter');
await page.waitForTimeout(3500);
console.log('frame src:', await page.evaluate(() => document.querySelector('#browserFrame').src.slice(-40)));
console.log('frame title:', await page.evaluate(() => { try { return document.querySelector('#browserFrame').contentDocument.title; } catch(e){ return 'UNREADABLE:'+e; } }));
const box = await page.locator('#browserFrame').boundingBox();
console.log('frame box:', JSON.stringify(box));
console.log('at-point:', await page.evaluate((pt) => { const el = document.elementFromPoint(pt.x, pt.y); return el ? el.tagName + '#' + el.id + '.' + el.className : 'NONE'; }, { x: box.x + box.width * 0.5, y: box.y + box.height * 0.9 }));
await page.mouse.click(box.x + box.width * 0.5, box.y + box.height * 0.9);
await page.waitForTimeout(600);
await page.keyboard.type('hello page', { delay: 30 });
await page.keyboard.press('Enter');
await page.waitForTimeout(1500);
console.log('activeElement:', await page.evaluate(() => document.activeElement.tagName + '#' + document.activeElement.id));
console.log('frame active:', await page.evaluate(() => { try { return document.querySelector('#browserFrame').contentDocument.activeElement.tagName + '#' + document.querySelector('#browserFrame').contentDocument.activeElement.id; } catch(e){ return 'UNREADABLE'; } }));
console.log('title now:', await page.evaluate(() => { try { return document.querySelector('#browserFrame').contentDocument.title; } catch(e){ return 'UNREADABLE'; } }));
await browser.close();
await fetch('http://localhost:1420/api/slot', { method: 'POST', headers: { 'content-type': 'application/json' }, body: JSON.stringify({ slot: 'A' }) });
