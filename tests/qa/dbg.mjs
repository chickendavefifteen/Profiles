import { firefox } from 'playwright';
const browser = await firefox.launch({ headless: true });
const page = await browser.newPage();
page.on('pageerror', e => console.log('PAGEERR', String(e)));
await page.goto('http://localhost:8123/src/?mode=lifeful', { waitUntil: 'networkidle' });
await page.waitForTimeout(1500);
await page.click('[data-close="pane-doc"]');
await page.waitForTimeout(800);
console.log('hidden after close:', await page.evaluate(() => document.querySelector('#pane-doc').className));
await page.click('#trashBtn');
await page.waitForTimeout(500);
console.log('trash html:', await page.evaluate(() => document.querySelector('#trashList').innerHTML.slice(0,200)));
await page.click('#trashList button');
await page.waitForTimeout(1800);
console.log('class after recover:', await page.evaluate(() => document.querySelector('#pane-doc').className));
console.log('layoutInit/hidden state:', await page.evaluate(async () => {
  const r = await fetch('/api/config').then(x=>x.json());
  return JSON.stringify(r.profile.layout) + ' closed=' + JSON.stringify(r.profile.closedPanes);
}));
await browser.close();
